// Generate 80 Glowing Fireflies scattered across 10,000px × 10,000px space
export function generateFireflies(): FireflyEntity[] {
  const fireflies: FireflyEntity[] = [];
  const colors = ['#fef08a', '#fde047', '#fed7aa', '#ddd6fe', '#bae6fd', '#f472b6'];

  for (let i = 1; i <= 80; i++) {
    const angle = i * 0.42;
    const r = 400 + i * 115;
    const baseX = 5000 + Math.cos(angle) * r;
    const baseY = 5000 + Math.sin(angle) * r;

    const clampedX = Math.max(300, Math.min(9700, baseX));
    const clampedY = Math.max(300, Math.min(9700, baseY));

    const zone = ZONES.find(
      (z) => clampedX >= z.minX && clampedX <= z.maxX && clampedY >= z.minY && clampedY <= z.maxY
    ) || ZONES[0];

    fireflies.push({
      id: `firefly_${i}`,
      x: clampedX,
      y: clampedY,
      baseX: clampedX,
      baseY: clampedY,
      collected: false,
      color: colors[i % colors.length],
      radius: 4.0 + (i % 3),
      pulsePhase: Math.random() * Math.PI * 2,
      floatAngle: Math.random() * Math.PI * 2,
      speed: 0.5 + Math.random() * 0.8,
      zoneId: zone.id,
    });
  }

  return fireflies;
}

