// Coffee Beans Generator
export function generateCoffeeBeans(): CoffeeBeanEntity[] {
  const beans: CoffeeBeanEntity[] = [];
  for (let i = 1; i <= 15; i++) {
    beans.push({
      id: `bean_${i}`,
      x: 7500 + (i % 5) * 160 + Math.sin(i) * 40,
      y: 4500 + Math.floor(i / 5) * 140 + Math.cos(i) * 40,
      collected: false,
    });
  }
  return beans;
}

