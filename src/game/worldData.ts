// 1. Generate 50 Glowing Fireflies scattered in 6000x6000px space
export function generateFireflies(): FireflyEntity[] {
  const fireflies: FireflyEntity[] = [];
  const colors = ['#fef08a', '#fde047', '#fed7aa', '#ddd6fe', '#bae6fd'];

  for (let i = 1; i <= 50; i++) {
    const angle = i * 0.42;
    const r = 350 + i * 95;
    const baseX = 3000 + Math.cos(angle) * r;
    const baseY = 3000 + Math.sin(angle) * r;

    const zone = ZONES.find(
      (z) => baseX >= z.minX && baseX <= z.maxX && baseY >= z.minY && baseY <= z.maxY
    ) || ZONES[0];

    fireflies.push({
      id: `firefly_${i}`,
      x: Math.max(200, Math.min(5800, baseX)),
      y: Math.max(200, Math.min(5800, baseY)),
      baseX: Math.max(200, Math.min(5800, baseX)),
      baseY: Math.max(200, Math.min(5800, baseY)),
      collected: false,
      color: colors[i % colors.length],
      radius: 4.0 + (i % 3),
      pulsePhase: Math.random() * Math.PI * 2,
      floatAngle: Math.random() * Math.PI * 2,
      speed: 0.5 + Math.random() * 0.8,
      zoneId: zone.id,
    });
  }

  return fireflies;
}

