// 4. Coffee Beans
export function generateCoffeeBeans(): CoffeeBeanEntity[] {
  const beans: CoffeeBeanEntity[] = [];
  for (let i = 1; i <= 10; i++) {
    beans.push({
      id: `bean_${i}`,
      x: 4200 + (i % 4) * 110 + Math.sin(i) * 30,
      y: 3000 + Math.floor(i / 4) * 90 + Math.cos(i) * 30,
      collected: false,
    });
  }
  return beans;
}

